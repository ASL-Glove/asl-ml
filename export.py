"""Quantize the trained model to int8 and generate the firmware headers.

    python export.py                                   # uses artifacts/model.keras
    python export.py --calib data/raw/cayden/s1/calib.json   # bake one wearer's calibration in

Writes artifacts/firmware/:
    model_data.h          the int8 .tflite model as a C array
    preprocess_config.h   constants from config.yaml + input quantization + calibration

Copy both into Code/Firmware/glove-firmware/ and rebuild. With model_data.h
present, the firmware switches from the stub classifier to the real model.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np

from preprocess import ROOT, emit_header, load_config

FLASH_BUDGET_KB = 600   # free flash after BLE (see NOTES.md)


def write_model_header(tflite: bytes, path: Path) -> None:
    lines = []
    for i in range(0, len(tflite), 12):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in tflite[i:i + 12]) + ",")
    path.write_text(
        "// AUTO-GENERATED by asl-ml/export.py. Do not edit by hand.\n"
        "#pragma once\n#define HAVE_ASL_MODEL 1\n\n"
        f"alignas(16) const unsigned char g_model_data[] = {{\n" + "\n".join(lines) + "\n};\n"
        f"const unsigned int g_model_data_len = {len(tflite)};\n"
    )


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--artifacts", default=str(ROOT / "artifacts"))
    ap.add_argument("--calib", help="calib.json to bake in as the firmware's default calibration")
    args = ap.parse_args()

    import tensorflow as tf

    cfg = load_config()
    art = Path(args.artifacts)
    model = tf.keras.models.load_model(art / "model.keras")
    rep = np.load(art / "rep_data.npy")

    def representative():
        for x in rep[:300]:
            yield [x[None].astype(np.float32)]

    conv = tf.lite.TFLiteConverter.from_keras_model(model)
    conv.optimizations = [tf.lite.Optimize.DEFAULT]
    conv.representative_dataset = representative
    conv.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    conv.inference_input_type = tf.int8
    conv.inference_output_type = tf.int8
    tflite = conv.convert()
    (art / "model.tflite").write_bytes(tflite)

    # Sanity check: int8 model agrees with the float model on the representative set.
    interp = tf.lite.Interpreter(model_content=tflite)
    interp.allocate_tensors()
    inp, outp = interp.get_input_details()[0], interp.get_output_details()[0]
    in_scale, in_zp = inp["quantization"]
    sample = rep[:200]
    agree = 0
    float_pred = model.predict(sample, verbose=0).argmax(1)
    for x, fp in zip(sample, float_pred):
        q = np.clip(np.round(x / in_scale + in_zp), -128, 127).astype(np.int8)[None]
        interp.set_tensor(inp["index"], q)
        interp.invoke()
        agree += int(interp.get_tensor(outp["index"])[0].argmax() == fp)

    fw = art / "firmware"
    fw.mkdir(parents=True, exist_ok=True)
    write_model_header(tflite, fw / "model_data.h")
    calib = json.loads(Path(args.calib).read_text()) if args.calib else None
    emit_header(cfg, fw / "preprocess_config.h", calib=calib,
                input_scale=float(in_scale), input_zero_point=int(in_zp))

    kb = len(tflite) / 1024
    print(f"int8 model: {kb:.1f} KB  ({kb / FLASH_BUDGET_KB:.1%} of ~{FLASH_BUDGET_KB} KB flash budget)")
    print(f"input quantization: scale={in_scale:.6f} zero_point={in_zp}")
    print(f"int8 vs float agreement on {len(sample)} windows: {agree / len(sample):.1%}")
    print(f"wrote {fw}/model_data.h and preprocess_config.h  -> copy into Code/Firmware/glove-firmware/")


if __name__ == "__main__":
    main()
